/**
 * Порядок разделов справки. Заявка — первой: с неё начинают все.
 *
 * `need` скрывает раздел от того, у кого этих экранов нет: рассказывать
 * сотруднику, как пользоваться «Журналом», значит отправлять его искать
 * пункт меню, которого он не увидит. Это удобство, а не защита — доступ
 * всё равно решает сервер.
 */
const GROUPS: { title: string; need?: Permission }[] = [
  { title: 'Заявка' },
  { title: 'Быстрее заполнить' },
  { title: 'Телефон и Telegram' },
  { title: 'Руководителю', need: 'view_reports' },
  { title: 'Администратору', need: 'manage_reference' },
];

export function Help() {
  const { can } = useAuth();
  const [query, setQuery] = useState('');

  const q = query.trim().toLowerCase();
  const items = q
    ? FAQ.filter((f) => f.q.toLowerCase().includes(q) || f.a.toLowerCase().includes(q))
    : FAQ;

  return (
    <>
      <PageHeader title="Справка" lead="Как проходит заявка и кто за что отвечает" />

      <div style={{ maxWidth: 440 }}>
        <label className="sr-only" htmlFor="help-search">
          Поиск по справке
        </label>
        <div style={{ position: 'relative', display: 'flex', alignItems: 'center' }}>
          <Icon
            name="ti-search"
            size={18}
            style={{ position: 'absolute', left: 12, color: 'var(--slate)', pointerEvents: 'none' }}
          />
          <input
            id="help-search"
            className="field"
            type="search"
            style={{ paddingLeft: 40 }}
            placeholder="Поиск по вопросам"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
          />
        </div>
      </div>

      {items.length === 0 ? (
        <EmptyState
          kicker="Ничего не найдено"
          title="По запросу ничего нет"
          note="Попробуйте другое слово или очистите поиск. Спорные случаи — к администратору системы."
          action={
            <button type="button" className="btn btn-secondary" onClick={() => setQuery('')}>
              Очистить поиск
            </button>
          }
        />
      ) : (
        GROUPS.map((group) => {
          if (group.need && !can(group.need)) return null;
          const inGroup = items.filter((f) => f.group === group.title);
          if (inGroup.length === 0) return null;
          return (
            <section key={group.title}>
              <div className="rubric">{group.title}</div>
              <div className="grid-auto">
                {inGroup.map((f) => (
                  <section
                    key={f.q}
                    className="card"
                    style={{ display: 'grid', gap: 12, alignContent: 'start' }}
                  >
                    <h2 className="label" style={{ margin: 0 }}>
                      {f.q}
                    </h2>
                    <p style={{ margin: 0 }}>{f.a}</p>
                  </section>
                ))}
              </div>
            </section>
          );
        })
      )}
    </>
  );
}
