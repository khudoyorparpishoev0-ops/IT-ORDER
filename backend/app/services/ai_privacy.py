"""Что из истории заявок можно показать этому человеку.

Одна точка, где решается вопрос «видно или не видно». Раскидывать такие
проверки по сервисам нельзя: однажды в новой подсказке забудут вычистить
имя, и сотрудник узнает, кто и на сколько закупался.

Правило заказчика, зафиксированное 10.09.2026: историю **всей компании**
использовать можно, но только как знание о материалах.

Показываем всем:
  название материала, модель, характеристики, единицу измерения, факт
  частого использования, факт использования на объекте.

Не показываем без права видеть чужие заявки:
  кто оформлял, суммы, комментарии, согласования, документы, действия
  другого сотрудника.

Правильно:   «UTP Cat6 Outdoor — часто используется на объекте Регар»
Неправильно: «Начиб заказывал этот кабель 6 сентября за 3 355 сомони»
"""

from __future__ import annotations

from app.core.permissions import Permission, has_permission
from app.db.models import Employee


def sees_others(employee: Employee) -> bool:
    """Можно ли показывать этому человеку чужие заявки как таковые."""
    return has_permission(employee.role, Permission.VIEW_ALL_REQUESTS)


def visible_employee_id(employee: Employee) -> int | None:
    """Чьи заявки человек вправе видеть. None — все.

    То же правило, что у списка заявок: границу навязывает сервер, а не
    параметр запроса.
    """
    return None if sees_others(employee) else employee.id


def strip_person(item: dict, employee: Employee) -> dict:
    """Убирает из подсказки всё, что относится к людям и деньгам.

    Материал остаётся, история вокруг него — нет. Возвращается новый
    словарь: править чужой объект на месте — надёжный способ однажды
    отдать почищенное одному и грязное другому.
    """
    if sees_others(employee):
        return dict(item)
    clean = dict(item)
    for field in ("employee", "employee_id", "amount", "comment", "decision_comment"):
        clean.pop(field, None)
    return clean
