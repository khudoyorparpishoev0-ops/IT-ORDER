"""Приведённое написание материала: по нему ищем, сравниваем и ловим дубли.

Люди пишут одно и то же десятью способами: «гофра16», «Гофра 16мм»,
«ГОФРА 16 ММ.». Для человека это один материал, для базы — пять разных
строк, и подсказки с отчётами разваливаются.

Поэтому у строки заявки два написания: `title` — как написал человек, его
и показываем всегда; `normalized_text` — приведённое, по нему идёт поиск
и сравнение. Подменять то, что человек написал, нельзя: отвечать за
заявку ему, а не нам.

Правила намеренно простые и предсказуемые: ни склонений, ни словаря
синонимов. Умная нормализация, которую нельзя объяснить в двух строках,
однажды склеит два разных материала, и никто не поймёт почему.
"""

from __future__ import annotations

import re

#: Степени в единицах: «м²» и «м2» — одно и то же.
_SUPERSCRIPT = str.maketrans({"²": "2", "³": "3"})

#: Всё, что не буква и не цифра, — разделитель. Точка в «шт.» и дефис в
#: «UTP-кабель» не должны делать написания разными.
_PUNCT = re.compile(r"[^0-9a-zа-я]+")

#: Граница буквы и цифры: «гофра16» → «гофра 16», «16мм» → «16 мм»,
#: «cat6» → «cat 6». Так «Cat6» и «Cat 6» сходятся в одно.
_JOINT = re.compile(r"(?<=[a-zа-я])(?=[0-9])|(?<=[0-9])(?=[a-zа-я])")


def normalize(text: str | None) -> str:
    """Приведённое написание. Пустая строка, если писать было нечего."""
    value = (text or "").casefold().replace("ё", "е")
    value = value.translate(_SUPERSCRIPT)
    value = _PUNCT.sub(" ", value)
    value = _JOINT.sub(" ", value)
    return " ".join(value.split())
